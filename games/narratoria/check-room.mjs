import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const context=vm.createContext({});
vm.runInContext(readFileSync(new URL('./room.js',import.meta.url),'utf8'),context);
const run=code=>JSON.parse(vm.runInContext(`JSON.stringify(${code})`,context));
const empty=run('normalizeRoom()');
assert.equal(empty.placements.length,3);
assert.equal(empty.wall,'wall_paper');
assert.equal(empty.floor,'floor_oak');
const legacy=run('normalizeRoom(undefined,{bookcase:"home_bookcase"},["home_bookcase"])');
assert.equal(legacy.placements.filter(p=>p.id.includes('book')).length,1);
assert(legacy.placements.some(p=>p.id==='home_bookcase'));
const malformed=run('normalizeRoom({owned:["fake","room_landscape"],wall:"floor_dark",floor:"fake",placements:[{id:"fake"},{id:"room_landscape",x:900,y:-5,w:Infinity,h:200},{id:"room_landscape"}]})');
assert.equal(malformed.placements.length,1);
assert.equal(malformed.wall,'wall_paper');
assert.equal(malformed.floor,'floor_oak');
const p=malformed.placements[0];
assert(p.x+p.w<=100 && p.y>=0 && p.y+p.h<=100);
const removed=run('normalizeRoom({placements:[],edited:true})');
assert.equal(removed.placements.length,0);
assert(removed.edited);
assert.deepEqual(run(`normalizeRoom(${JSON.stringify(legacy)}, {bookcase:"home_bookcase"},["home_bookcase"])`),legacy);
console.log('Habitación: valores iniciales, migración sin duplicados, saneamiento, objetos retirados y persistencia correctos.');
