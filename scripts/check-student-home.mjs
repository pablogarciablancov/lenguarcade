import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const html=fs.readFileSync('apps-script/LenguArcade_Alumno.html','utf8');
const source=html.slice(html.indexOf('  function homePct('),html.indexOf('  function renderHomeOverview('));
const context={window:{},esc:value=>String(value??'').replace(/[&<>"]/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;'}[c]))};
vm.createContext(context);vm.runInContext(source,context);
const mission={title:'Encuentra sustantivos',gameId:'lexitrama',missionType:'sessions',target:10,progress:6};
const game={gameId:'lexitrama',nombre:'Lexitrama',locked:false};
let dashboard={missions:[mission],games:[game]};
let output=context.homeMissionHtml(dashboard);
assert.match(output,/Entrar en Lexitrama/);assert.match(output,/6 \/ 10/);assert.match(output,/aria-valuenow="60"/);
game.locked=true;game.buttonLabel='Sesión cerrada';output=context.homeMissionHtml(dashboard);
assert.match(output,/Sesión cerrada/);assert.doesNotMatch(output,/data-home-game=/);
game.locked=false;assert.match(context.homeMissionHtml(dashboard),/data-home-game="lexitrama"/);
assert.match(context.homeMissionHtml({missions:[{...mission,gameId:''}],games:[]}),/Elegir un juego disponible/);
assert.match(context.homeMissionHtml({missions:[],games:[]}),/Sin misiones pendientes/);
assert.match(context.homeMissionHtml({missions:[{...mission,completed:true}],games:[]}),/¡Misiones completadas!/);
const urgent={...mission,title:'Plazo próximo',dueAt:'2026-10-13T10:00:00Z'},later={...mission,title:'Destacada',featured:true,dueAt:'2026-10-20T10:00:00Z'};
assert.equal(context.homePendingMissions({missions:[later,urgent]})[0].title,'Plazo próximo');
assert.equal(context.homePendingMissions({missions:[mission,{...mission,featured:true,title:'Destacada'}]})[0].title,'Destacada');
assert.match(context.homeMissionHtml({missions:[{...mission,title:'<script>alert(1)</script>'}],games:[]}),/&lt;script&gt;/);
