import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const sceneText=require('../games/rayuela/scene-text.js');
const choices=(...labels)=>labels.map((text,index)=>({id:'choice_'+index,text,targetId:'target_'+index}));
const options=choices('Aceptas la copa','Rechazas la copa');
const intro='Estás en un bar y de repente un señor viejo te invita a una copa.';
const original=intro+'\nAceptas la copa\nRechazas la copa';
assert.equal(sceneText(original,options),intro,'captura: solo queda la escena');
assert.equal(sceneText(intro+' Aceptas la copa o rechazas la copa.',options),intro,'opciones en la misma línea');
assert.equal(sceneText(intro+'\nRechazas la copa.\nAceptas la copa.',options),intro,'orden distinto de botones');
assert.equal(sceneText(intro+'\n ACEPTAS   la copa.\n rechazas la copa! ',options),intro,'espacios, mayúsculas y puntuación');
assert.equal(sceneText(intro+'\n¿Que haces?\nAceptas la copa\nRechazas la copa',options),intro+'\n¿Que haces?','no reformula preguntas ni tildes');
assert.equal(sceneText(intro+'\n¿Qué haces?\nAceptas la copa\nRechazas la copa',options),intro,'pregunta independiente');
assert.equal(sceneText('Aceptas la copa\nRechazas la copa',options),'','una casilla solo de opciones no necesita texto duplicado');
assert.equal(sceneText('Aceptas la copa. El camarero se marcha.',options),'Aceptas la copa. El camarero se marcha.','no borra menciones dentro de la narración');
assert.equal(sceneText(intro+'\nAceptas la copa',options),intro+'\nAceptas la copa','no elimina listas parciales');
assert.equal(sceneText('Decides continuar.',choices('Continuar')),'Decides continuar.','conserva continuaciones únicas');
assert.equal(sceneText('Tu decisión\nTú decides',choices('Tú decisión','Tú decides')),'Tu decisión\nTú decides','no confunde tildes diacríticas');
assert.equal(sceneText('',options),'');
assert.equal(sceneText(null,options),'');
const three=choices('Abres la puerta','Subes al tejado','Buscas la llave');
assert.equal(sceneText('Ves una casa. Abres la puerta, subes al tejado o buscas la llave.',three),'Ves una casa.','tres decisiones');
// Run the actual player renderer with its DOM dependencies stubbed, including escaping.
const html=fs.readFileSync(new URL('../games/rayuela/index.html',import.meta.url),'utf8');
assert(html.includes('<script src="./scene-text.js?v=20261027"></script>'));
const block=html.slice(html.indexOf('function renderPlayNode(){'),html.indexOf('\nfunction renderEnding('));
const content={innerHTML:'',querySelectorAll(){return [];}},labels={};
const node={id:'start',text:original,title:'Inicio',choices:options};
const sandbox={window:{RayuelaSceneText:sceneText},playState:{nodeId:'start',path:['start'],inventory:[],vars:{}},project:{discoveredEndings:[]},gallerySession:{},getNode:()=>node,nodeLockReason:()=>'',applyNodeEffects(){},updateInventoryButton(){},isEnding:()=>false,typeDef:()=>({label:'Inicio'}),choiceLockReason:()=>'',esc:s=>String(s).replace(/[&<>\"]/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;'}[c])),$:id=>id==='playContent'?content:(labels[id]??={}),Math};
vm.createContext(sandbox);vm.runInContext(block+'\nrenderPlayNode();',sandbox);
assert.equal((content.innerHTML.match(/Aceptas la copa/g)||[]).length,1,'solo un botón Aceptas');
assert.equal((content.innerHTML.match(/Rechazas la copa/g)||[]).length,1,'solo un botón Rechazas');
assert(content.innerHTML.includes('<div class="storyText">'+intro+'</div>'));
assert.equal(node.text,original,'el guardado/editor conserva el original');
node.text='Aceptas la copa\nRechazas la copa';vm.runInContext('renderPlayNode();',sandbox);assert(!content.innerHTML.includes('Esta escena todavía'));
node.text='';vm.runInContext('renderPlayNode();',sandbox);assert(content.innerHTML.includes('Esta escena todavía'));
console.log('Rayuela: decisiones solo en botones; escena intacta, listas completas, continuidad, tildes y render real correctos.');
